#!/usr/bin/env bash
# Regenerates THIRD_PARTY_LICENSES.md from Cargo.lock: every crate linked into
# agstudio or ddar (normal and build dependencies, all targets), with the
# licence its manifest declares. Run after changing dependencies.
set -euo pipefail
cd "$(dirname "$0")/.."
out=THIRD_PARTY_LICENSES.md
rows=$(cargo tree --locked --workspace -e normal,build --prefix none --format '{p}|{l}|{r}' --target all \
  | grep -v -e '(\*)' -e '^$' | grep -v -E '^(alphageometry-rs|ag-studio) ' | sed 's/ (proc-macro)//' | sort -u)
{
  echo "# Third-party licences"
  echo
  echo "Generated by \`deploy/third-party-licenses.sh\` from \`Cargo.lock\`; do not edit by hand."
  echo "These Rust crates are compiled into the \`agstudio\` and \`ddar\` binaries. Each is used"
  echo "under the licence (or, for \"A OR B\", one of the licences) its manifest declares;"
  echo "the full texts ship in each crate's source. \`libsqlite3-sys\` builds the bundled"
  echo "SQLite library, which is in the public domain. Fonts: \`ag-studio/assets/fonts/FONT-LICENSES.txt\`."
  echo
  echo "| Crate | Version | Licence | Source |"
  echo "|---|---|---|---|"
  while IFS='|' read -r pkg lic repo; do
    name=${pkg% v*}
    ver=${pkg##* v}
    echo "| $name | $ver | ${lic:-see source} | ${repo:-https://crates.io/crates/$name} |"
  done <<< "$rows"
} > "$out"
echo "wrote $out ($(printf '%s\n' "$rows" | wc -l) crates)"
